// Writes umami.md (git-ignored): every Umami event this site can send, for setting up the Umami dashboard.
// Run after a build: node scripts/umami-events.ts
import { readFileSync, writeFileSync } from 'node:fs';

const tools: { slug: string; name: string }[] = JSON.parse(
  readFileSync('build/tools.json', 'utf8'),
);
const row = (cells: string[]) => `| ${cells.join(' | ')} |`;

const text = `# Umami events for img-tools.fyi

Generated by \`node scripts/umami-events.ts\` from the built site. Do not commit this file.

## How the site sends events

- The page header loads Umami's script (\`https://cloud.umami.is/script.js\`, website ID
  \`65f9c9af-18ef-45a8-9f6f-52f3987c5eba\`) with automatic tracking off. The site calls \`umami.track()\` itself, so
  every event passes the privacy checks first.
- Nothing is sent from other hostnames than img-tools.fyi and www.img-tools.fyi, or when the browser sends
  Do Not Track or Global Privacy Control (opt-in builds: until the visitor switches statistics on).
- Page views are sent as ordinary Umami page views.

## Usage count per tool: \`<tool>:upload\`

One event is sent each time a visitor adds file(s) to a tool (a drop, a choice in the file dialog, a paste, or a
file handed over from the home page). It carries **no properties**. Count these to rank tools by use.

${row(['Tool', 'Event name'])}
${row(['---', '---'])}
${tools.map((t) => row([t.name, `\`${t.slug}:upload\``])).join('\n')}

## Other events (optional)

Every tool can also send the following, each as \`<tool>:<action>\` (for example \`convert-image:run\`):

${row(['Action', 'Sent when'])}
${row(['---', '---'])}
${row(['run', 'The visitor starts the work'])}
${row(['done', 'The work finished'])}
${row(['error', 'The work failed (property \`reason\` is a fixed code)'])}
${row(['download', 'A result was downloaded'])}
${row(['download-all', 'All results were downloaded as a ZIP'])}
${row(['copy', 'A value was copied'])}
${row(['unsupported', 'The browser cannot do what the tool needs'])}

Allowed properties are listed on https://img-tools.fyi/privacy/ (files bucket, formats, quality rounded to 5,
duration bucket, error code, browser capability flags). File names, contents and sizes are never sent.
`;

writeFileSync('umami.md', text);
console.log(`umami.md written for ${tools.length} tools.`);
